import type { DrawingAction } from '@drawing-games/drawing-model'

import type { GuessScoreBreakdown } from '../scoring'
import type {
  TeamId,
  TeamScores,
  WinStreak,
  WordDifficulty,
  WordReplacementReason,
} from '../types'
import type {
  MatchSummaryRecord,
  MemberMatchStats,
  PlayerWordMemory,
  WordHistoryEvent,
} from './records'
import type { RoomSettings, WordLengthMode } from './settings'

/* -------------------------------------------------------------------------- */
/* Authoritative state (server only — never sent to a browser as-is)          */
/* -------------------------------------------------------------------------- */

export const ROOM_STATE_VERSION = 1 as const

export type RoomPhase =
  'lobby' | 'word-draft' | 'drawing' | 'round-results' | 'showdown' | 'stats'

export type MemberKind = 'human' | 'bot'

export interface RoomMember {
  /** Opaque id generated by the realtime layer (humans) or reducer (bots). */
  readonly id: string
  readonly kind: MemberKind
  readonly displayName: string
  readonly team: TeamId
  readonly joinedAtMs: number
  /** Presence only. Bots are always connected. */
  readonly connected: boolean
  readonly lastSeenAtMs: number
  /** Lobby readiness. Bots are always ready. Cleared by settings changes. */
  readonly ready: boolean
  /** Linked quick-account id (normalized username), or null for guests. */
  readonly accountId: string | null
  readonly memory: PlayerWordMemory
  /**
   * Internal. Set when a member leaves mid-match: they stay in `members` so
   * history and final views keep their name, but are excluded from rosters,
   * views, and commands, and are removed when a new match or the lobby starts.
   */
  readonly left?: boolean
}

/** A concrete draft card. Copied from the word pool when offered. */
export interface DraftOption {
  readonly wordId: string
  readonly term: string
  readonly difficulty: WordDifficulty
  readonly packId: string
  readonly packName: string
  /** Drawer-only helper text. Never projected to guessers or opponents. */
  readonly definition: string
  /** Extra accepted answers (normalized by the matcher). */
  readonly aliases: readonly string[]
}

export interface DraftReplacement {
  readonly reason: WordReplacementReason
  readonly actorId: string
  readonly replacedWordId: string
  readonly replacementWordId: string
  readonly atMs: number
}

/**
 * - `correct`: matches the answer or an accepted alias/plural.
 * - `close`: within a small edit distance of the answer.
 * - `partial`: contains at least one whole word of a multi-word answer.
 * - `wrong`: anything else.
 */
export type GuessVerdict = 'correct' | 'close' | 'partial' | 'wrong'

export interface GuessRecord {
  readonly id: string
  readonly memberId: string
  /** Trimmed text as typed. Hidden from every view once verdict is correct. */
  readonly text: string
  readonly verdict: GuessVerdict
  readonly atMs: number
}

export interface TeamSolution {
  readonly guesserId: string
  readonly atMs: number
  readonly points: number
  readonly breakdown: GuessScoreBreakdown
}

export interface HintState {
  readonly revealed: boolean
  readonly revealedAtMs: number | null
  /** memberId -> approve. Only eligible human guessers may vote. */
  readonly votes: Readonly<Record<string, boolean>>
}

export interface TeamRoundState {
  readonly team: TeamId
  readonly drawerId: string
  readonly options: readonly DraftOption[]
  readonly replacements: readonly DraftReplacement[]
  readonly chosenWordId: string | null
  readonly chosenBy: 'drawer' | 'auto' | null
  /** Stable id for this round's canvas, e.g. `m1-r3-A`. */
  readonly canvasId: string
  /** Completed strokes accepted from the drawer (stroke.end operations). */
  readonly strokeCount: number
  readonly firstStrokeAtMs: number | null
  /** Bounded team-private guess feed (most recent last). */
  readonly guesses: readonly GuessRecord[]
  readonly solution: TeamSolution | null
  readonly hint: HintState
}

export interface RoundState {
  readonly number: number
  readonly startedAtMs: number
  readonly draftDeadlineAtMs: number
  readonly drawingStartedAtMs: number | null
  readonly drawingDeadlineAtMs: number | null
  readonly endedAtMs: number | null
  readonly teams: Readonly<Record<TeamId, TeamRoundState>>
  readonly scoresBeforeRound: TeamScores
  readonly streakBeforeRound: WinStreak | null
  /** Set when the round ends: the team with more round points, or null. */
  readonly winner: TeamId | null
  readonly shutdownBonus: number
}

export interface ShowdownTeamState {
  readonly team: TeamId
  /** This team's previously chosen words, shuffled independently. */
  readonly cards: readonly DraftOption[]
  /** Index of the active card; equals cards.length when finished. */
  readonly cardIndex: number
  readonly drawerId: string | null
  /** Relay rotation counter for this team. */
  readonly relayTurn: number
  /** Canvas for the active card, e.g. `m1-sd-A-2`. */
  readonly canvasId: string
  readonly cardStartedAtMs: number
  readonly strokeCount: number
  readonly firstStrokeAtMs: number | null
  /** Guess feed for the active card only. */
  readonly guesses: readonly GuessRecord[]
  /** Set when every card is cleared. */
  readonly finishedAtMs: number | null
}

export interface ShowdownState {
  readonly startedAtMs: number
  readonly deadlineAtMs: number
  readonly teams: Readonly<Record<TeamId, ShowdownTeamState>>
  readonly firstClearTeam: TeamId | null
  readonly endedAtMs: number | null
}

export interface SurrenderVoteState {
  readonly team: TeamId
  readonly roundNumber: number
  readonly votes: Readonly<Record<string, boolean>>
}

export interface MatchState {
  readonly number: number
  readonly startedAtMs: number
  readonly scores: TeamScores
  readonly completedRounds: number
  readonly winStreak: WinStreak | null
  /** Completed drawer turns per team; drawer = roster[turns % roster.length]. */
  readonly drawerTurns: Readonly<Record<TeamId, number>>
  /** The active round, or the round just completed during round-results. */
  readonly round: RoundState | null
  /** Every completed normal round, oldest first. */
  readonly history: readonly RoundState[]
  readonly showdown: ShowdownState | null
  readonly showdownPoints: TeamScores
  readonly surrender: SurrenderVoteState | null
  /** Largest positive lead each team held after any round. */
  readonly largestLead: TeamScores
  readonly endedAtMs: number | null
  readonly endedReason: 'completed' | 'surrender' | null
  /** null while running or on a tie. */
  readonly winner: TeamId | null
  readonly stats: Readonly<Record<string, MemberMatchStats>>
  readonly withBots: boolean
  /** Internal. Per-member guess rate limiting for the current canvas. */
  readonly guessLimits?: Readonly<Record<string, GuessLimit>>
}

/** Internal rate-limit counter; resets whenever `scope` (a canvas id) changes. */
export interface GuessLimit {
  readonly scope: string
  readonly count: number
  readonly lastAtMs: number
}

/** Room-wide anti-repeat memory. Survives rematches; reset never. */
export interface RoomWordMemory {
  /** Chosen (drawn) word ids, oldest first, capped. */
  readonly usedWordIds: readonly string[]
  /** wordId -> draft counter value when it was last offered. */
  readonly offeredAt: Readonly<Record<string, number>>
  /** Pack ids of recently chosen words, newest first, capped. */
  readonly recentPackIds: readonly string[]
  /** Incremented once per team draft (and per replacement draw). */
  readonly draftCounter: number
}

/** Bot runtime. The reducer owns its shape; nothing outside reads it. */
export interface BotScheduleItem {
  readonly atMs: number
  readonly botId: string
  readonly action:
    | { readonly type: 'draft.pick' }
    | { readonly type: 'draw.next-stroke'; readonly canvasId: string }
    | {
        readonly type: 'guess'
        readonly canvasId: string
        readonly text: string
        readonly correct: boolean
      }
}

export interface BotRuntimeState {
  readonly schedule: readonly BotScheduleItem[]
  /** canvasId -> number of planned strokes already drawn by the bot. */
  readonly strokesDrawn: Readonly<Record<string, number>>
}

export interface RoomState {
  readonly version: typeof ROOM_STATE_VERSION
  readonly roomCode: string
  readonly createdAtMs: number
  /** Monotonic state version; increments on every accepted change. */
  readonly seq: number
  /** uint32 PRNG state; all randomness flows through it. */
  readonly rngState: number
  readonly phase: RoomPhase
  readonly phaseStartedAtMs: number
  readonly phaseDeadlineAtMs: number | null
  readonly hostId: string | null
  readonly settings: RoomSettings
  /** Join order. Team rosters are derived by filtering this list in order. */
  readonly members: readonly RoomMember[]
  readonly nextBotNumber: number
  readonly match: MatchState | null
  readonly wordMemory: RoomWordMemory
  readonly bots: BotRuntimeState
  readonly lastActivityAtMs: number
}

/* -------------------------------------------------------------------------- */
/* Commands (already authenticated by the realtime layer)                     */
/* -------------------------------------------------------------------------- */

export type RoomCommand =
  | {
      readonly type: 'member.join'
      readonly memberId: string
      readonly displayName: string
      readonly accountId: string | null
      readonly memory: PlayerWordMemory
      readonly preferredTeam?: TeamId
    }
  | {
      readonly type: 'member.presence'
      readonly memberId: string
      readonly connected: boolean
    }
  | { readonly type: 'member.leave'; readonly memberId: string }
  | {
      readonly type: 'member.link-account'
      readonly memberId: string
      readonly accountId: string | null
      readonly memory: PlayerWordMemory
    }
  | {
      readonly type: 'member.rename'
      readonly memberId: string
      readonly displayName: string
    }
  | {
      readonly type: 'lobby.set-team'
      readonly actorId: string
      readonly memberId: string
      readonly team: TeamId
    }
  | { readonly type: 'lobby.shuffle-teams'; readonly actorId: string }
  | {
      readonly type: 'lobby.set-ready'
      readonly actorId: string
      readonly ready: boolean
    }
  | {
      readonly type: 'lobby.update-settings'
      readonly actorId: string
      readonly patch: Partial<RoomSettings>
    }
  | {
      readonly type: 'lobby.add-bot'
      readonly actorId: string
      readonly team: TeamId
    }
  | {
      readonly type: 'lobby.remove-member'
      readonly actorId: string
      readonly memberId: string
    }
  | { readonly type: 'match.start'; readonly actorId: string }
  | {
      readonly type: 'draft.select'
      readonly actorId: string
      readonly wordId: string
    }
  | {
      readonly type: 'draft.replace'
      readonly actorId: string
      readonly wordId: string
      readonly reason: WordReplacementReason
    }
  | {
      readonly type: 'drawing.ops'
      readonly actorId: string
      readonly ops: readonly DrawingAction[]
    }
  | {
      readonly type: 'guess.submit'
      readonly actorId: string
      readonly text: string
    }
  | {
      readonly type: 'hint.vote'
      readonly actorId: string
      readonly approve: boolean
    }
  | {
      readonly type: 'surrender.vote'
      readonly actorId: string
      readonly approve: boolean
    }
  | { readonly type: 'round.continue'; readonly actorId: string }
  | {
      readonly type: 'match.rematch'
      readonly actorId: string
      readonly mode: 'same-settings' | 'change-settings'
    }

export type RoomCommandType = RoomCommand['type']

/* -------------------------------------------------------------------------- */
/* Effects (the realtime layer executes these after persisting state)         */
/* -------------------------------------------------------------------------- */

export type RoomEffect =
  /** Start a fresh, empty canvas (new round, new showdown card). */
  | {
      readonly type: 'canvas.reset'
      readonly canvasId: string
      readonly team: TeamId
    }
  /** Apply accepted drawing operations to a canvas and fan them out. */
  | {
      readonly type: 'canvas.ops'
      readonly canvasId: string
      readonly team: TeamId
      readonly ops: readonly DrawingAction[]
      readonly origin: 'member' | 'bot'
      readonly actorId: string
    }
  /** Private feedback for the guesser only. */
  | {
      readonly type: 'guess.feedback'
      readonly memberId: string
      readonly text: string
      readonly verdict: GuessVerdict
    }
  | {
      readonly type: 'account.words'
      readonly accountId: string
      readonly events: readonly WordHistoryEvent[]
    }
  | {
      readonly type: 'account.match'
      readonly accountId: string
      readonly summary: MatchSummaryRecord
    }

export type RoomErrorCode = 'NOT_ALLOWED' | 'BAD_COMMAND' | 'ROOM_FULL'

export interface RoomError {
  readonly code: RoomErrorCode
  /** Short, human-readable, safe to show the actor. Never contains secrets. */
  readonly message: string
}

/**
 * Commands always advance expired deadlines first, so even a rejected
 * command can return a newer state and effects that must be applied.
 */
export type RoomCommandResult =
  | {
      readonly ok: true
      readonly state: RoomState
      readonly effects: readonly RoomEffect[]
    }
  | {
      readonly ok: false
      readonly state: RoomState
      readonly effects: readonly RoomEffect[]
      readonly error: RoomError
    }

export interface RoomAdvanceResult {
  readonly state: RoomState
  readonly effects: readonly RoomEffect[]
}

/** Which canvases a viewer may receive in full vs. as a coarse preview. */
export interface CanvasAccess {
  readonly full: readonly string[]
  readonly preview: readonly string[]
}

/** A coarse, irreversible opponent preview. `cells` is row-major. */
export interface CanvasPreview {
  readonly cols: number
  readonly rows: number
  /** Six-digit hex color of the dominant ink in each cell, or null. */
  readonly cells: readonly (string | null)[]
}

/* -------------------------------------------------------------------------- */
/* Viewer projection (what one browser receives as `room.snapshot`)           */
